test("cancellation remote clears pickup and delivery without reward or energy refund", function()
    local accept = prompt("Missão principal")
    local pickup = prompt("Retirar pacote")
    local deliver = prompt("Entregar pacote")
    for _, stage in ipairs({ "Pickup", "Deliver" }) do
        local p = newPlayer({ Cash = 100, Reputation = 5, MissionCompletions = 3 })
        trigger(accept, p)
        if stage == "Deliver" then trigger(pickup, p) end
        local energy = p:GetAttribute("Energy")
