local count = 0
local failures = 0
local function expect(actual, expected, label)
    assert(actual == expected, (label or "value") .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function test(name, callback)
    count += 1
    local ok, message = pcall(callback)
    if ok then
        print("PASS " .. name)
    else
        failures += 1
        print("FAIL " .. name .. ": " .. tostring(message))
    end
end
local function prompt(action, markerName)
    local names = { ["Retirar pacote"] = "PackagePickup", ["Entregar pacote"] = "PackageDropoff", ["Iniciar turno"] = "FastFood", ["Comprar lanche"] = "SnackShop" }
    createMissionMarker(city, markerName or names[action] or action, vector(0, 0, 0), action, "Test job")
    return lastPrompt
end
local function trigger(target, player)
    clock += 3
    target.fire(player)
end
local function unchanged(player, before)
    for name, value in pairs(before) do
        if name ~= "StatusText" then expect(player:GetAttribute(name), value, name) end
    end
end
local function snapshot(player) return table.clone(player.attributes) end

