test("income cadence belongs to each owner rather than a shared server minute", function()
    local first = newPlayer({ Cash = 2000 })
    local second = newPlayer({ Cash = 2000 })
    local buy = prompt("Comprar")
    trigger(buy, first)
    local firstPurchase = clock
    clock = firstPurchase + 30
    buy.fire(second)
    for _, elapsed in ipairs({ 60, 90, 120 }) do
        clock = firstPurchase + elapsed
        updatePlayerTimers(first, clock)
        updatePlayerTimers(second, clock)
        expect(first:GetAttribute("Cash"), elapsed == 120 and 1300 or 1225)
        expect(second:GetAttribute("Cash"), elapsed == 60 and 1150 or 1225)
    end
    expect(first:GetAttribute("NextIncomeAt"), firstPurchase + 180)
    expect(second:GetAttribute("NextIncomeAt"), firstPurchase + 150)
end)

